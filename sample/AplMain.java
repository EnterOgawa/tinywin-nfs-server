public final class AplMain {
	//--------------------------------------------------------------------------
	/**
	 * 書式見本のインスタンス生成を防ぎます。<br><br>
	 *
	 * <p>メソッド名称： コンストラクタ</p>
	 */
	//--------------------------------------------------------------------------
	private AplMain() {
	}

	//--------------------------------------------------------------------------
	/**
	 * 表示用の名前を整えます。<br><br>
	 *
	 * <p>メソッド名称： 表示名整形</p>
	 *
	 * @param name	入力名
	 * @return 整形した表示名
	 */
	//--------------------------------------------------------------------------
	public static String formatName( String name) {
		// 名前が指定されていない場合
		if( name == null) {
			return "" ;
		}

		return name.trim() ;
	}
}
